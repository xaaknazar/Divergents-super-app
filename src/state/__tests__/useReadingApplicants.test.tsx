test('definitive command rejection clears uncertain state and reloads permissions', async () => {
  send.mockRejectedValueOnce(new ReadingApiError('Это заявка другой команды', 403));
  const h = await renderHook(() => useReadingApplicants('club'));
  await waitFor(() => expect(h.result.current.data).toBeTruthy());
  details.mockResolvedValue({ ...readingApplicantsFixture, applications: [] });
  await act(async () => { await h.result.current.decide('demo-applicant', 'approved'); });
  expect(h.result.current.pendingDecision).toBeUndefined(); expect(h.result.current.decisionError).toBe('Это заявка другой команды');
  expect(h.result.current.data?.applications).toEqual([]);
});
test('returning after a background decision settles restores retry without a stuck busy state', async () => {
  let done!: (value: { ok: true }) => void;
  send.mockImplementationOnce(() => new Promise(resolve => { done = resolve; }));
  const h = await renderHook(() => useReadingApplicants('club'));
  await waitFor(() => expect(h.result.current.data).toBeTruthy());
  await act(async () => { void h.result.current.decide('demo-applicant', 'approved'); });
  await waitFor(() => expect(send).toHaveBeenCalledTimes(1));
  mockFocused = false; await h.rerender({});
  await act(async () => { done({ ok: true }); });
  mockFocused = true; await h.rerender({});
  await waitFor(() => expect(h.result.current.busy).toBe(false));
  await act(async () => { h.result.current.retryDecision(); });
  await waitFor(() => expect(h.result.current.message).toBe('Участник принят в команду.'));
  expect(send.mock.calls[1][1]).toEqual(send.mock.calls[0][1]);
});
