import { act, renderHook, waitFor } from '@testing-library/react-native';
import { useReadingApplicants } from '../useReadingApplicants';
import { fetchReadingDetail, sendReadingCommand, ReadingApiError } from '../../data/reading';
import { fetchReadingApplicant } from '../../data/readingApplicants';
import { readingApplicantFixture, readingApplicantsFixture } from '../../storybook/readingApplicantFixtures';
let mockAccount = 'captain', mockUuid = 0, mockFocused = true;
jest.mock('@clerk/clerk-expo', () => ({ useAuth: () => ({ userId: mockAccount, getToken: async () => `token-${mockAccount}` }) }));
jest.mock('@react-navigation/native', () => ({ useFocusEffect: (fn: () => void) => require('react').useEffect(() => mockFocused ? fn() : undefined, [fn, mockFocused]) }));
jest.mock('../../data/api', () => ({ API_BASE: 'https://example.test' }));
jest.mock('../../data/reading', () => ({ ...jest.requireActual('../../data/reading'), fetchReadingDetail: jest.fn(), sendReadingCommand: jest.fn() }));
jest.mock('../../data/readingApplicants', () => ({ fetchReadingApplicant: jest.fn() }));
jest.mock('expo-crypto', () => ({ randomUUID: () => `operation-${++mockUuid}` }));
jest.mock('../readingNative', () => { throw new Error('Applicants must never initialize a native timer'); });
const details = jest.mocked(fetchReadingDetail), profile = jest.mocked(fetchReadingApplicant), send = jest.mocked(sendReadingCommand);
beforeEach(() => { mockAccount = 'captain'; mockUuid = 0; mockFocused = true;
  details.mockReset().mockResolvedValue(readingApplicantsFixture); profile.mockReset().mockResolvedValue(readingApplicantFixture);
  send.mockReset().mockResolvedValue({ ok: true });
});
test('review-only hook reads list, loads one selected profile and rejects unlisted member ids', async () => {
  const h = await renderHook(() => useReadingApplicants('club'));
  await waitFor(() => expect(h.result.current.data).toBe(readingApplicantsFixture));
  expect(profile).not.toHaveBeenCalled();
  await act(async () => { await h.result.current.select('someone-else'); await h.result.current.decide('someone-else', 'approved'); });
  expect(profile).not.toHaveBeenCalled(); expect(send).not.toHaveBeenCalled();
  await act(async () => { await h.result.current.select('demo-applicant'); });
  expect(profile).toHaveBeenCalledWith('token-captain', 'club', 'demo-applicant');
  expect(h.result.current.applicant).toBe(readingApplicantFixture);
});
test('uncertain decision retries the exact request, blocks opposite choice, then acknowledges success', async () => {
  send.mockRejectedValueOnce(new Error('Нет подтверждения'));
  const h = await renderHook(() => useReadingApplicants('club'));
  await waitFor(() => expect(h.result.current.data).toBeTruthy());
  await act(async () => { await h.result.current.decide('demo-applicant', 'approved'); });
  expect(h.result.current.pendingDecision).toBe('approved');
  expect(h.result.current.message).toBeUndefined();
  await act(async () => { await h.result.current.decide('demo-applicant', 'rejected'); });
  expect(send).toHaveBeenCalledTimes(1);
  // The server may already have committed although the acknowledgement was lost.
  details.mockResolvedValue({ ...readingApplicantsFixture, applications: [] });
  await act(async () => { await h.result.current.reload(); });
  await act(async () => { h.result.current.retryDecision(); });
  await waitFor(() => expect(h.result.current.message).toBe('Участник принят в команду.'));
  expect(send.mock.calls[1][1]).toEqual(send.mock.calls[0][1]);
  expect(send.mock.calls[0][1]).toMatchObject({ action: 'review', challengeId: 'club', memberId: 'demo-applicant', decision: 'approved', operationId: 'operation-1' });
  expect(h.result.current.pendingDecision).toBeUndefined();
});
test('late questionnaire response cannot reappear after closing it', async () => {
  let done!: (value: typeof readingApplicantFixture) => void;
  profile.mockImplementationOnce(() => new Promise(resolve => { done = resolve; }));
  const h = await renderHook(() => useReadingApplicants('club'));
  await waitFor(() => expect(h.result.current.data).toBeTruthy());
  await act(async () => { void h.result.current.select('demo-applicant'); });
  await waitFor(() => expect(profile).toHaveBeenCalledTimes(1));
  await act(async () => { h.result.current.close(); done(readingApplicantFixture); });
  expect(h.result.current.applicant).toBeUndefined(); expect(h.result.current.selectedId).toBeUndefined();
});
