// Что показывать в трекере: серверный день плюс то, что ещё не дошло до сервера.
//
// Вынесено из ChallengeContext отдельным модулем ради проверяемости: правило
// слияния — это то место, где ошибка не видна глазами. Тип Challenge берётся
// только как тип, поэтому модуль остаётся чистым и не тянет за собой ни сеть,
// ни React Native.
import type { Challenge } from '../data/community';

/** Одна неотправленная отметка. */
export interface PendingUpdate {
  taskId: string;
  value?: number;
  done?: boolean;
}

/** Очередь неотправленных отметок за конкретный день конкретного челленджа. */
export interface SavedPending {
  id: string;
  day: number;
  updates: PendingUpdate[];
}

/**
 * Наложить на серверный день то, что ещё НЕ ДОШЛО до сервера.
 *
 * ЗАЧЕМ ИМЕННО ОЧЕРЕДЬ, А НЕ СНИМОК ДНЯ. Раньше поверх свежих серверных задач
 * накладывался локальный снимок целиком, и он побеждал всегда. Для галочки это
 * значило буквально следующее: человек отмечал «без сахара» на сайте, сервер
 * честно записывал `done: true`, приложение получало `true` — и тут же затирало
 * его сохранённым с утра `false`. Отметка была в базе, в зачёте и у товарищей
 * по команде, но в своём приложении человек её не видел до конца дня и
 * отмечался второй раз. То же самое происходило со страницами и шагами,
 * введёнными на сайте.
 *
 * Правильная граница: сервер — источник правды, а у устройства есть ровно одно
 * знание, которого у сервера нет, — отметки из очереди, которые ещё не
 * отправлены. Их и накладываем, остальное берём как пришло. Подтверждённая
 * отметка уходит из очереди (см. sendTask), и экран сразу начинает показывать
 * серверное значение.
 */
export function applyPending(base: Challenge, pending: SavedPending | null): Challenge {
  if (!pending || pending.id !== base.id || pending.day !== base.currentDay) return base;
  if (pending.updates.length === 0) return base;
  return {
    ...base,
    tasks: base.tasks.map((t) => {
      const u = pending.updates.find((x) => x.taskId === t.id);
      if (!u) return t;
      // Значение из очереди берём как есть, а не максимумом с серверным: это
      // намеренное действие человека, включая исправление вниз («не 300
      // страниц, а 30») и осознанное снятие галочки.
      if (t.kind === 'metric') return u.value === undefined ? t : { ...t, current: u.value };
      return u.done === undefined ? t : { ...t, done: u.done };
    }),
  };
}
