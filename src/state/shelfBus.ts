// Небольшая шина событий для книжной полки.
//
// Полку («Хочу прочитать» / «Читаю» / «Прочитал», прогресс и оценка) читает
// каждый экран сам, своим useState, поэтому копий состояния несколько.
// Раньше из-за этого изменения с экрана книги появлялись в «Моих книгах» и в
// каталоге только после перезапуска приложения.
//
// Теперь любой код, который изменил полку или оценку, вызывает
// `emitShelfChanged()`, и ВСЕ смонтированные экраны перечитывают данные сразу.
type Listener = () => void;

const listeners = new Set<Listener>();

export function onShelfChanged(fn: Listener): () => void {
  listeners.add(fn);
  return () => { listeners.delete(fn); };
}

export function emitShelfChanged(): void {
  // Копия списка: обработчик может отписаться прямо во время рассылки.
  for (const fn of Array.from(listeners)) {
    try { fn(); } catch { /* один сломанный подписчик не должен ломать остальные */ }
  }
}
