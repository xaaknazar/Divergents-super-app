// Награда за 1 место команды в челлендже — знак Divergents на золоте.
//
// ПОЧЕМУ НЕ КУБОК-ЭМОДЗИ. 🏆 выглядит одинаково в любом приложении и ничего не
// говорит о том, кто награду выдал. Здесь тот же знак, что на заставке и в
// шапке трекера: его узнают, и он означает именно эту награду, а не «какое-то
// достижение вообще».
//
// ПОЧЕМУ БЕЛЫЙ ЗНАК НА СПЛОШНОМ ЗОЛОТЕ, А НЕ ЗОЛОТОЙ НА ПРОЗРАЧНОМ. Значок
// живёт в строке рядом с именем и в обычном состоянии имеет 15 точек. На таком
// размере золотой знак на бледно-золотой подложке сливается в пятно; белый на
// сплошном золоте читается силуэтом. Контраст здесь — не украшение, а
// единственный способ остаться различимым.
//
// Золото — единственное место в приложении, где оно есть. Поэтому значок
// заметен, хотя занимает меньше строчной буквы.
import React from 'react';
import { View } from 'react-native';
import { Logo } from './Logo';

/** Фирменное золото награды. Держим здесь, чтобы экраны брали один и тот же. */
export const AWARD_GOLD = '#E0A21A';
/** Тёмное золото — для знака на светлом фоне и текста рядом с ним. */
export const AWARD_GOLD_DEEP = '#8A5D05';

export function AwardBadge({ size = 16 }: { size?: number }) {
  return (
    <View
      accessibilityLabel="Награда за первое место в челлендже"
      style={{
        width: size,
        height: size,
        borderRadius: size / 2,
        backgroundColor: AWARD_GOLD,
        alignItems: 'center',
        justifyContent: 'center',
      }}
    >
      {/* Знак занимает 68% круга: меньше — теряется, больше — упирается в край
          и читается как клякса. */}
      <Logo size={Math.round(size * 0.68)} body="#fff" head="#fff" />
    </View>
  );
}
