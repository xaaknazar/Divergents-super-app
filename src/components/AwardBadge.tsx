// Награда за 1 место команды в челлендже — золотой кубок.
//
// ПОЧЕМУ НЕ ЭМОДЗИ 🏆. Эмодзи рисует система: на iOS он один, на Android
// другой, размера не слушается, цвет не меняется, и рядом с текстом всегда
// сидит чуть выше строки. Здесь кубок из той же иконочной библиотеки, что и
// весь остальной интерфейс, — он подчиняется размеру, цвету и выравниванию.
//
// ПОЧЕМУ ЦВЕТ ЗАВИСИТ ОТ ТЕМЫ. Кубок стоит прямо на фоне экрана, без подложки.
// Одно и то же золото на белом выглядит выцветшим, а на чёрном — кричащим,
// поэтому берём светлое золото для тёмной темы и глубокое для светлой. Это не
// два разных цвета, а один и тот же, взятый с нужной стороны шкалы.
import React from 'react';
import { View } from 'react-native';
import { SF } from './SFIcon';
import { useTheme } from '../theme/ThemeContext';

/** Фирменное золото награды. Держим здесь, чтобы экраны брали один и тот же. */
export const AWARD_GOLD = '#E0A21A';
/** Глубокое золото — на светлом фоне. */
export const AWARD_GOLD_DEEP = '#8A5D05';

export function AwardBadge({ size = 16 }: { size?: number }) {
  const { isDark } = useTheme();
  return (
    // Обёртка нужна только ради подписи для озвучки: иконка сама по себе
    // доступности не несёт, а без подписи значок для незрячего просто исчезает.
    <View accessible accessibilityLabel="Награда за первое место в челлендже">
      <SF name="trophy.fill" size={size} color={isDark ? AWARD_GOLD : AWARD_GOLD_DEEP} />
    </View>
  );
}
