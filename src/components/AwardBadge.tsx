// Награда за 1 место команды в челлендже — золотой кубок.
//
// ПОЧЕМУ НЕ ЭМОДЗИ 🏆. Эмодзи рисует система: на iOS он один, на Android
// другой, размер не слушается, цвет не меняется, и рядом с текстом он всегда
// сидит чуть выше строки. Здесь кубок из той же иконочной библиотеки, что и
// весь остальной интерфейс, — он подчиняется размеру, цвету и выравниванию.
//
// ПОЧЕМУ БЕЛЫЙ НА СПЛОШНОМ ЗОЛОТЕ. Значок живёт в строке рядом с именем и в
// обычном состоянии имеет 15 точек. На таком размере золотой кубок на
// бледно-золотой подложке сливается в пятно; белый силуэт на сплошном золоте
// читается сразу. Контраст здесь не украшение, а единственный способ остаться
// различимым.
//
// Золото — единственное место в приложении, где оно есть. Поэтому значок
// заметен, хотя занимает меньше строчной буквы.
import React from 'react';
import { View } from 'react-native';
import { SF } from './SFIcon';

/** Фирменное золото награды. Держим здесь, чтобы экраны брали один и тот же. */
export const AWARD_GOLD = '#E0A21A';
/** Тёмное золото — для знака на светлом фоне и текста рядом с ним. */
export const AWARD_GOLD_DEEP = '#8A5D05';

export function AwardBadge({ size = 16 }: { size?: number }) {
  return (
    <View
      accessibilityLabel="Награда за первое место в челлендже"
      style={{
        width: size,
        height: size,
        borderRadius: size / 2,
        backgroundColor: AWARD_GOLD,
        alignItems: 'center',
        justifyContent: 'center',
      }}
    >
      {/* Кубок занимает 62% круга: меньше — теряется, больше — упирается
          ручками в край и теряет силуэт. */}
      <SF name="trophy.fill" size={Math.round(size * 0.62)} color="#fff" />
    </View>
  );
}
